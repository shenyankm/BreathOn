import { test, expect } from '@playwright/test'

test.use({ storageState: 'test-results/.auth/admin.json' })

test('scenario templates preserve bindings, save focused stages and support group filters', async ({ page }) => {
  const doctors = await (await page.request.get('/api/catalog/doctor')).json()
  const doctor = doctors.find((row: any)=>row.status==='published')
  const created = await page.request.post('/api/catalog/rubric', { headers: { Origin: 'http://127.0.0.1:5187' }, data: { name: '场景配置回归量表', dimensions: [{ key: 'communication', label: '沟通', weight: 100, anchors: ['未观察','待改进','基本完成','充分完成','清晰完整'], requires_content: false }] } })
  expect(created.ok(), await created.text()).toBeTruthy()
  const draft = await created.json()
  const published = await page.request.post(`/api/catalog/rubric/${draft.id}/publish`, { headers: { Origin: 'http://127.0.0.1:5187' }, data: { version: draft.version } })
  expect(published.ok(), await published.text()).toBeTruthy()
  const rubric = await published.json()
  expect(doctor).toBeTruthy(); expect(rubric).toBeTruthy()
  await page.goto('/admin#workspace?tab=scenario')
  const generator = page.getByRole('button', { name: 'AI 生成拜访场景', exact: true })
  await expect(generator).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('region', { name: 'AI 生成拜访场景', exact: true })).toBeHidden()
  await generator.click()
  await expect(page.getByRole('region', { name: 'AI 生成拜访场景', exact: true })).toBeVisible()
  await generator.click()
  await expect(page.getByRole('region', { name: 'AI 生成拜访场景', exact: true })).toBeHidden()
  await page.getByRole('button', { name: '手动创建场景', exact: true }).click()
  const form = page.getByRole('form', { name: '训练场景配置' })
  await form.getByLabel('情境类型', { exact: true }).click()
  await expect(page.getByRole('option')).toHaveCount(12)
  await page.getByRole('option', { name: '超说明书问题', exact: true }).click()
  await page.getByRole('button', { name: '填入该类训练模板' }).click()
  await expect(form.getByRole('textbox', { name: '训练目标', exact: true })).toHaveValue(/识别超出有效说明书/)
  await expect(form.getByLabel('建议时长（秒）', { exact: true })).toHaveValue('180')
  await expect(form.getByRole('textbox', { name: '核心异议与追问（每行一项）', exact: true })).not.toHaveValue('')
  await expect(form.getByRole('textbox', { name: '可观察的完成标准（每行一项）', exact: true })).not.toHaveValue('')
  await expect(form.getByRole('checkbox', { name: '安全沟通', exact: true })).toBeChecked()
  await expect(form.getByRole('checkbox', { name: '研究介绍', exact: true })).not.toBeChecked()
  await form.getByLabel('场景名称', { exact: true }).fill('场景细分回归测试')
  await form.getByLabel('产品', { exact: true }).fill('软件测试主题')
  await form.getByLabel('疾病／治疗领域', { exact: true }).fill('教学演示')
  await form.getByLabel('医生角色', { exact: true }).click()
  await page.getByRole('option', { name: `${doctor.display_name} · 已发布`, exact: true }).click()
  await form.getByLabel('评价量表', { exact: true }).click()
  await page.getByRole('option', { name: `${rubric.name} · 已发布`, exact: true }).click()
  const saved = page.waitForResponse(response=>response.url().endsWith('/api/catalog/scenario')&&response.request().method()==='POST')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  const response = await saved
  expect(response.ok(), await response.text()).toBeTruthy()
  const scene = await response.json()
  expect(scene.situation).toBe('off_label_request')
  expect(scene.stages).toEqual(['safety','objections','closing'])
  expect(scene.status).toBe('draft')
  await page.goto('/admin#workspace?tab=scenario')
  await page.getByLabel('搜索场景', { exact: true }).fill('场景细分回归测试')
  await page.getByLabel('训练方向', { exact: true }).click()
  await page.getByRole('option', { name: '安全与合规', exact: true }).click()
  const list = page.getByRole('region', { name: '训练场景列表', exact: true })
  await expect(list.getByRole('button')).toHaveCount(1)
  await list.getByRole('button').click()
  await expect(list.getByRole('button')).toHaveAttribute('data-variant', 'secondary')
  await expect(page.getByLabel('情境类型', { exact: true })).toContainText('超说明书问题')
  for (const width of [1440,768,390]) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(()=>window.scrollTo(0,0))
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
    await page.screenshot({ path: test.info().outputPath(`scenario-template-${width}.png`) })
  }
})

test('five module groups replace cross-module tabs and rubric rows stay compact', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/admin')
  const navigation = page.getByRole('navigation', { name: '后台导航', exact: true })
  await expect(navigation.getByRole('button')).toHaveCount(4)
  await expect(navigation.getByRole('link')).toHaveCount(1)
  const training = navigation.getByRole('button', { name: '训练管理', exact: true })
  await training.click()
  await expect(training).toHaveAttribute('aria-expanded', 'true')
  await training.click()
  await expect(training).toHaveAttribute('aria-expanded', 'false')
  await expect(navigation.getByRole('link', { name: '评分标准', exact: true })).toBeHidden()
  await expect(page.locator('main').getByRole('heading', { level: 1 })).toHaveText('总览')
  await training.click()
  await navigation.getByRole('link', { name: '评分标准', exact: true }).click()
  await expect(page.locator('main').getByRole('heading', { level: 1 })).toHaveText('评分标准')
  await expect(navigation.getByRole('link', { name: '评分标准', exact: true })).toHaveAttribute('aria-current', 'page')
  await training.click()
  await expect(training).toHaveAttribute('aria-expanded', 'false')
  await training.press('Enter')
  await expect(training).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('navigation', { name: '训练管理导航' })).toHaveCount(0)
  const list = page.getByRole('region', { name: '评分标准列表', exact: true })
  expect(await list.evaluate(element=>element.dataset.slot)).not.toBe('card')
  const row = list.getByRole('button').first()
  await expect(row).toBeVisible()
  expect((await row.boundingBox())!.height).toBeLessThan(90)
  await row.click()
  await expect(row).toHaveAttribute('data-variant', 'secondary')
  await page.screenshot({ path: test.info().outputPath('rubric-selected-desktop.png') })
  await page.setViewportSize({ width: 390, height: 900 })
  await page.getByLabel('管理内容', { exact: true }).click()
  await page.getByRole('option', { name: '训练资料', exact: true }).click()
  await expect(page.locator('main').getByRole('heading', { level: 1 })).toHaveText('训练资料')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  await page.screenshot({ path: test.info().outputPath('module-navigation-mobile.png') })
})
