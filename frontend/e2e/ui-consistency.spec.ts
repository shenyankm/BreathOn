import { test, expect } from '@playwright/test'

for (const width of [1440, 768, 390]) test(`UI hierarchy, selection and form sizing at ${width}px`, async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width, height: 900 }, hasTouch: width < 1024, reducedMotion: 'reduce' })
  const page = await context.newPage()
  try {
    await page.goto('http://127.0.0.1:5187/admin')
    const username = page.getByLabel('账号', { exact: true })
    const password = page.getByLabel('密码', { exact: true })
    await expect(username).toBeVisible()
    expect((await username.boundingBox())!.height).toBe((await password.boundingBox())!.height)
    await username.fill('e2e-admin')
    await password.fill('local-e2e-only-password')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    const main = page.locator('main')
    await expect(main.getByRole('heading', { level: 1 })).toBeVisible()
    for (const hash of ['admin', 'admin?section=drug', 'admin?section=doctor', 'admin?section=audiences',
      'admin?section=policy', 'admin?section=training', 'admin?section=review', 'admin?section=records',
      'admin?section=settings', 'workspace?tab=doctor', 'settings']) {
      await page.goto(`http://127.0.0.1:5187/admin#${hash}`)
      const heading = main.getByRole('heading', { level: 1 })
      await expect(heading).toHaveCount(1)
      await expect(heading).toHaveCSS('font-size', '24px')
      await expect(heading).toHaveCSS('font-weight', '600')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    }
    await page.goto('http://127.0.0.1:5187/admin#admin?section=doctor')
    const doctors = page.getByRole('region', { name: '医生列表', exact: true })
    const doctor = doctors.getByRole('button').first()
    await expect(doctor).toBeVisible()
    expect((await doctor.boundingBox())!.y).toBeLessThan(540)
    expect((await doctor.boundingBox())!.height).toBeLessThan(140)
    const nextDoctor = doctors.getByRole('button').nth(1)
    await nextDoctor.click()
    await expect(nextDoctor).toHaveAttribute('aria-pressed', 'true')
    await expect(doctor).toHaveAttribute('aria-pressed', 'false')
    const doctorDetail = page.getByRole('region', { name: '医生画像详情', exact: true })
    await expect(doctorDetail).toBeVisible()
    await expect(doctorDetail).toHaveCSS('box-shadow', 'none')
    await page.screenshot({ path: test.info().outputPath(`doctors-${width}.png`), fullPage: true })
    await page.goto('http://127.0.0.1:5187/admin#workspace?tab=doctor')
    await expect(main.getByRole('heading', { level: 1 })).toHaveText('医生角色')
    await expect(page.getByRole('navigation', { name: '训练管理导航' })).toHaveCount(0)
    await expect(page.getByRole('link', { name: '返回医生列表', exact: true })).toHaveAttribute('href', '#admin?section=doctor')
    await page.goto('http://127.0.0.1:5187/admin#admin?section=drug')
    const list = page.getByRole('region', { name: '药品列表' })
    const first = list.getByRole('button').nth(0)
    const second = list.getByRole('button').nth(1)
    await first.click()
    await expect(first).toHaveAttribute('aria-pressed', 'true')
    await page.mouse.move(0, 0)
    await expect(first).toHaveAttribute('data-variant', 'secondary')
    await second.click()
    await expect(first).toHaveAttribute('aria-pressed', 'false')
    await expect(first).toHaveAttribute('data-variant', 'ghost')
    await expect(second).toHaveAttribute('aria-pressed', 'true')
    await expect(second).toHaveAttribute('data-variant', 'secondary')
    expect(await list.evaluate(element => element.parentElement!.closest('[data-slot="card"]') === null)).toBeTruthy()
    if (width === 390) expect((await list.boundingBox())!.width).toBeGreaterThan(300)
    await page.screenshot({ path: test.info().outputPath(`catalogue-${width}.png`), fullPage: true })
  } finally {
    await context.close()
  }
})
